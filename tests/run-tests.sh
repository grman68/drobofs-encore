#!/bin/bash
# Integration test for dist/encore.tgz on a fake DroboFS (ARM via qemu-user).
#   tests/run-tests.sh
# Covers: install layout, self-test, smb.conf generation, testparm, service.sh
# start/stop (bind-mount takeover), SMB3 + encryption with smbclient, web API,
# and a syscall audit of smbd against the Linux 2.6.22 ARM syscall table.
set -uo pipefail
cd "$(dirname "$0")/.."
docker run --rm -i --privileged -v "$PWD":/proj:ro drobofs-test bash -s <<'EOS'
set -uo pipefail
APP=/mnt/DroboFS/Shares/DroboApps/encore
DRI=/mnt/DroboFS
PASS=0; FAILN=0
ok()   { echo "  PASS  $*"; PASS=$((PASS+1)); }
bad()  { echo "  FAIL  $*"; FAILN=$((FAILN+1)); }
check() { local d=$1; shift; if "$@" >/tmp/check.out 2>&1; then ok "$d"; else bad "$d"; sed 's/^/        /' /tmp/check.out | tail -15; fi; }

# ---- fake DroboFS environment
for a in ifconfig killall pidof setsid; do command -v $a >/dev/null || ln -s /bin/busybox /usr/local/bin/$a; done
mkdir -p $APP $DRI/System/samba/conf $DRI/System/samba/security $DRI/SystemLogs $DRI/Shares/Public $DRI/Shares/TimeMachine /etc/avahi/services /var/log
tar -xzf /proj/dist/encore.tgz -C $APP
cat > /etc/avahi/services/afpd.service <<'X'
<?xml version="1.0" standalone='no'?><service-group><name replace-wildcards="yes">%h</name><service><type>_afpovertcp._tcp</type><port>548</port></service></service-group>
X
mkdir -p /var/samba
echo "netbios name = Drobo-FS" > /var/samba/netbios.conf
cat > /etc/.backup_smb.conf <<'X'
server string = Drobo FS (Samba V. %v)
socket options = TCP_NODELAY
local master = no
encrypt passwords = yes
dns proxy = no
security = user
use mmap = yes
use sendfile = yes
map to guest = bad password
force user = root
force group = root
load printers = no
unix extensions = no
veto files = /.AppleDesktop/.AppleDB/.AppleDouble/Network Trash Folder/
X
cat > $DRI/System/samba/conf/smb.conf <<'X'
# DroboNAS config file generated by generateConfigFile
[global]
  workgroup = WORKGROUP
  log file = /mnt/DroboFS/SystemLogs/samba/logs/smb.log
  lock dir = /mnt/DroboFS/System/samba/security
  pid directory = /mnt/DroboFS/System/samba/security
  private dir = /mnt/DroboFS/System/samba/security
  include = /etc/.backup_smb.conf
  include = /var/samba/netbios.conf
[Public]
path = /mnt/DroboFS/Shares/Public
read only = no
guest ok = yes
public = yes
browseable = yes
vfs objects = /lib/vfs/readahead.so
[TimeMachine]
path = /mnt/DroboFS/Shares/TimeMachine
read only = no
valid users = admin
write list = admin
vfs objects = /lib/vfs/readahead.so
X
useradd -M -s /bin/false admin 2>/dev/null
printf '#!/bin/sh\necho stock-smbd "$@" >> /tmp/stock.log\n' > /sbin/smbd; printf '#!/bin/sh\necho stock-nmbd "$@" >> /tmp/stock.log\n' > /sbin/nmbd
chmod +x /sbin/smbd /sbin/nmbd
echo "Mock fs ready"

echo "== Install"
check "service.sh present and executable" test -x $APP/service.sh
check "loader is private uClibc" grep -a -q "$APP/lib/ld-uClibc.so.0" $APP/sbin/smbd
check "smbd -V runs" $APP/sbin/smbd -V
check "lua + cjson + luaposix load" env LUA_CPATH="$APP/lib/lua/5.4/?.so" LUA_PATH="$APP/share/lua/5.4/?.lua;$APP/share/lua/5.4/?/init.lua" $APP/bin/lua -e 'require("cjson"); require("posix.unistd"); print("ok")'
check "openssl runs" $APP/bin/openssl version
check "rsync runs" $APP/bin/rsync --version
check "lighttpd runs" $APP/sbin/lighttpd -v
$APP/sbin/smbd -V

echo "== Users"
cat > /tmp/pw.conf <<X
[global]
passdb backend = tdbsam:$DRI/System/samba/security/passdb.tdb
private dir = $DRI/System/samba/security
lock directory = /tmp/pwpriv
state directory = /tmp/pwpriv
cache directory = /tmp/pwpriv
X
mkdir -p /tmp/pwpriv
check "smbpasswd -a admin" sh -c "printf 'testpass123\ntestpass123\n' | $APP/bin/smbpasswd -c /tmp/pw.conf -a -s admin"
check "user stored in tdbsam passdb.tdb" test -s $DRI/System/samba/security/passdb.tdb

echo "== service.sh start"
mkdir -p $APP/var
echo "SMB_LOG_LEVEL='2'" > $APP/var/settings.conf
echo '{"TimeMachine":{"timemachine":true,"tm_max_size":"500G","recycle":true,"hidden":false,"encrypt":"required"}}' > $APP/var/shares.json
check "service.sh start" sh $APP/service.sh start
sleep 4
cat $APP/var/log/encore.log | sed 's/^/        log: /'
check "generated smb.conf exists" test -s $APP/var/etc/smb.conf
check "readahead.so stripped" sh -c "! grep -q readahead $APP/var/etc/smb.conf"
check "includes expanded (netbios name, force user)" sh -c "grep -q 'netbios name = Drobo-FS' $APP/var/etc/smb.conf && grep -q 'force user = root' $APP/var/etc/smb.conf"
check "Samba 4 uses a private copy of passdb.tdb" sh -c "grep -q 'passdb backend = tdbsam:$APP/var/samba/private/passdb.tdb' $APP/var/etc/smb.conf && test -s $APP/var/samba/private/passdb.tdb"
check "TimeMachine share has fruit:time machine" grep -q 'fruit:time machine = yes' $APP/var/etc/smb.conf
check "testparm accepts config" $APP/bin/testparm -s $APP/var/etc/smb.conf
check "/sbin/smbd is bind-mounted" grep -qE ' (/usr)?/sbin/smbd ' /proc/mounts
check "smbd running" sh -c "kill -0 \$(cat $DRI/System/samba/security/smbd.pid)"
check "pid file where nasd looks" sh -c "kill -0 \$(cat $DRI/System/samba/security/smbd-smb.conf.pid)"
ls $DRI/System/samba/security/
check "avahi services bind-mounted" grep -q ' /etc/avahi/services ' /proc/mounts
check "avahi _adisk record for TimeMachine" grep -q 'adVN=TimeMachine' /etc/avahi/services/encore-smb.service
check "stock afpd.service preserved" test -f /etc/avahi/services/afpd.service

echo "== SMB protocol"
SC="$APP/bin/smbclient -s $APP/var/etc/smb.conf"
check "list shares (SMB3)" $SC -L localhost -U admin%testpass123 -m SMB3
check "SMB3_11 + encryption to TimeMachine" sh -c "$SC //localhost/TimeMachine -U admin%testpass123 -m SMB3_11 --client-protection=encrypt -c 'mkdir enc; put /etc/hostname enc/h.txt; ls enc/*'"
check "guest access to Public" sh -c "$SC //localhost/Public -N -m SMB3 -c 'put /etc/hostname g.txt; ls'"
check "SMB1 refused by default" sh -c "! $SC -L localhost -U admin%testpass123 -m NT1 -c quit"
check "recycle bin keeps deleted files" sh -c "$SC //localhost/TimeMachine -U admin%testpass123 -m SMB3 -c 'del enc/h.txt' && find $DRI/Shares/TimeMachine/#recycle -name h.txt | grep -q ."
check "named streams via streams_depot" sh -c "$SC //localhost/TimeMachine -U admin%testpass123 -m SMB3 -c 'put /etc/hostname s.txt; put /etc/hostname s.txt:extra; allinfo s.txt' | grep -q ':extra:'"
$APP/bin/smbstatus -b -s $APP/var/etc/smb.conf | head -8

echo "== Web API"
C="curl -sk -c /tmp/cj -b /tmp/cj"
U=https://localhost:8443
check "HTTPS serves UI" sh -c "$C $U/ | grep -q 'Encore NAS'"
check "session unauthenticated" sh -c "$C $U/api/session | grep -q '\"authenticated\":false'"
check "POST without X-Encore is rejected" sh -c "$C -X POST $U/api/login -d '{}' | grep -q 'X-Encore'"
check "wrong password rejected" sh -c "$C -H 'X-Encore: 1' -X POST $U/api/login -d '{\"user\":\"admin\",\"password\":\"nope\"}' | grep -q 'Wrong'"
check "login as admin (NT hash check)" sh -c "$C -H 'X-Encore: 1' -X POST $U/api/login -d '{\"user\":\"admin\",\"password\":\"testpass123\"}' | grep -q '\"ok\":true'"
check "overview" sh -c "$C $U/api/overview | tee /tmp/ov.json | grep -q '\"mode\":\"encore\"'"
head -c 600 /tmp/ov.json; echo
check "shares lists TimeMachine with options" sh -c "$C $U/api/shares | grep -q '\"timemachine\":true'"
check "connections" sh -c "$C $U/api/connections | grep -q connections"
check "users (from tdbsam via pdbedit)" sh -c "$C $U/api/users | grep -q '\"name\":\"admin\"'"
check "login is case-insensitive (Admin)" sh -c "curl -sk -H 'X-Encore: 1' -X POST $U/api/login -d '{\"user\":\"Admin\",\"password\":\"testpass123\"}' | grep -q '\"ok\":true'"
check "logs" sh -c "$C '$U/api/logs?name=encore&lines=20' | grep -q text"
check "invalid setting rejected" sh -c "$C -H 'X-Encore: 1' -X PUT $U/api/settings -d '{\"SMB_ENCRYPT\":\"lol\"}' | grep -q Invalid"
check "change min protocol to SMB3_00" sh -c "$C -H 'X-Encore: 1' -X PUT $U/api/settings -d '{\"SMB_MIN_PROTOCOL\":\"SMB3_00\"}' | grep -q '\"ok\":true'"
sleep 2
check "SMB2.1 now refused" sh -c "! $SC -L localhost -U admin%testpass123 -m SMB2_10 -c quit"
check "share option update" sh -c "$C -H 'X-Encore: 1' -X PUT $U/api/shares/Public -d '{\"recycle\":true,\"encrypt\":\"default\"}' | grep -q '\"ok\":true'"
check "unknown share 404" sh -c "$C -H 'X-Encore: 1' -X PUT $U/api/shares/Nope -d '{}' | grep -q 'No such share'"
check "revert to stock Samba" sh -c "$C -H 'X-Encore: 1' -X POST $U/api/samba -d '{\"action\":\"stock\"}' | grep -q '\"ok\":true'"
check "bind mount gone after revert" sh -c "! grep -qE ' (/usr)?/sbin/smbd ' /proc/mounts"
check "stock smbd re-launched" grep -q 'stock-smbd -s' /tmp/stock.log
check "back to Samba 4" sh -c "$C -H 'X-Encore: 1' -X POST $U/api/samba -d '{\"action\":\"encore\"}' | grep -q '\"mode\":\"encore\"'"
check "logout" sh -c "$C -H 'X-Encore: 1' -X POST $U/api/logout | grep -q ok && $C $U/api/overview | grep -q 'Not signed in'"

echo "== service.sh stop"
check "service.sh stop" sh $APP/service.sh stop
check "no bind mounts left" sh -c "! grep -qE ' (/usr)?/sbin/(smbd|nmbd) | /etc/avahi/services ' /proc/mounts"

echo "== Syscall audit (smbd under qemu-arm -strace vs Linux 2.6.22)"
for f in $DRI/System/samba/security/*.pid; do [ -f "$f" ] && kill -9 $(cat $f) 2>/dev/null; done; sleep 2
(qemu-arm -strace -D /tmp/strace.log $APP/sbin/smbd -F --no-process-group -s $APP/var/etc/smb.conf >/dev/null 2>&1 &)
sleep 12
$SC //localhost/TimeMachine -U admin%testpass123 -m SMB3_11 --client-protection=encrypt -c 'put /etc/hostname a.txt; ls; del a.txt' >/dev/null 2>&1
sleep 3; kill $(cat $DRI/System/samba/security/smbd.pid) 2>/dev/null; sleep 2
python3 - /tmp/strace.log /proj/tests/syscalls-2.6.22-arm.txt <<'PY'
import re, sys, collections
log, table = sys.argv[1], sys.argv[2]
have = {}
for line in open(table):
    n, name = line.split()[:2]
    have[name] = int(n)
ok = {k for k, v in have.items() if k != 'ni_syscall'} | {'_newselect', 'mmap2', 'fstat64', 'stat64', 'lstat64', 'fcntl64', 'getdents64', 'statfs64', 'fstatfs64', 'ftruncate64', 'truncate64', 'rt_sigaction', 'rt_sigprocmask', 'exit_group', 'set_tls', 'cacheflush', 'breakpoint', 'usr26', 'usr32', 'getuid32', 'geteuid32', 'getgid32', 'getegid32', 'setresuid32', 'setresgid32', 'setgroups32', 'getgroups32', 'chown32', 'fchown32', 'lchown32', 'setuid32', 'setgid32', 'setreuid32', 'setregid32', 'getresuid32', 'getresgid32', 'setfsuid32', 'setfsgid32', 'pread64', 'pwrite64', 'sendfile64', 'llseek', '_llseek'}
# names in the kernel table carry wrapper suffixes; strip them
ok |= {re.sub(r'_wrapper$', '', k) for k in ok}
used = collections.Counter()
unknown = collections.Counter()
for line in open(log, errors='replace'):
    m = re.match(r'\d+ (\w+)\(', line)
    if m: used[m.group(1)] += 1
    m = re.search(r'Unknown syscall (\d+)', line)
    if m: unknown[m.group(1)] += 1
# kernel table uses new*/old* entry names and getrlimit for ugetrlimit
alias = {'ugetrlimit': 'getrlimit'}
def known(k):
    return k in ok or ('new' + k) in ok or alias.get(k) in ok
missing = sorted(k for k in used if not known(k))
print(f"  distinct syscalls used: {len(used)}")
if len(used) < 60:
    print("  WARNING: trace looks truncated; last lines:")
    for line in open(log, errors='replace').readlines()[-6:]: print('    |', line.rstrip()[:150])
print(f"  not available on 2.6.22: {missing or 'none'}")
if unknown: print(f"  unknown to qemu: {dict(unknown)}")
for k in missing:
    for line in open(log, errors='replace'):
        if re.match(rf'\d+ {k}\(', line):
            print('    e.g.', line.strip()[:160]); break
PY

echo
echo "RESULT: $PASS passed, $FAILN failed"
EOS
