#!/bin/bash
# Runs Encore inside a chroot of the real DroboFS root filesystem (BusyBox 1.14,
# glibc 2.5, stock Samba 3.4.4) under qemu, to catch firmware-userland quirks.
#   tools/extract-firmware.sh v1.2.7.tdz   (once)
#   tests/run-chroot-tests.sh
set -uo pipefail
cd "$(dirname "$0")/.."
[ -f tests/fw/drobofs-rootfs.tar.gz ] || { echo "run tools/extract-firmware.sh first"; exit 1; }
docker run --rm -i --privileged -v "$PWD":/proj:ro drobofs-test bash -s <<'EOS'
set -uo pipefail
R=/rootfs; APP=/mnt/DroboFS/Shares/DroboApps/encore; DRI=/mnt/DroboFS
PASS=0; FAILN=0
ok()  { echo "  PASS  $*"; PASS=$((PASS+1)); }
bad() { echo "  FAIL  $*"; FAILN=$((FAILN+1)); }
check() { local d=$1; shift; if "$@" >/tmp/c.out 2>&1; then ok "$d"; else bad "$d"; sed 's/^/        /' /tmp/c.out | tail -12; fi; }
dev() { chroot $R /bin/sh -c "$*"; }          # run a command "on the Drobo"

mkdir -p $R && tar -xzf /proj/tests/fw/drobofs-rootfs.tar.gz -C $R
mkdir -p $R/var $R/proc; mount -t proc proc $R/proc; mount --bind /dev $R/dev; mount -t tmpfs tmpfs $R/var
mkdir -p $R/var/run $R/var/log $R/var/lock $R/var/samba $R/tmp
mkdir -p $R$DRI/System/samba/conf $R$DRI/System/samba/security $R$DRI/SystemLogs/samba/logs $R$DRI/Shares/Public $R$APP
echo "netbios name = Drobo-FS" > $R/var/samba/netbios.conf
cat > $R$DRI/System/samba/conf/smb.conf <<X
# DroboNAS config file generated by generateConfigFile
[global]
  workgroup = WORKGROUP
  log file = $DRI/SystemLogs/samba/logs/smb.log
  lock dir = $DRI/System/samba/security
  pid directory = $DRI/System/samba/security
  state directory = $DRI/System/samba/security
  cache directory = /var/samba
  private dir = $DRI/System/samba/security
  include = /etc/.backup_smb.conf
  include = /var/samba/netbios.conf
[Public]
path = $DRI/Shares/Public
read only = no
guest ok = yes
public = yes
vfs objects = /lib/vfs/readahead.so
X
echo "Admin:x:1000:1000:admin:/:/bin/false" >> $R/etc/passwd
printf '[Private]\npath = %s/Shares/Private\nguest ok = no\nvalid users = Admin\nwrite list = Admin\nvfs objects = /lib/vfs/readahead.so\n' $DRI >> $R$DRI/System/samba/conf/smb.conf
mkdir -p $R$DRI/Shares/Private
cp /proj/dist/encore.tgz $R$DRI/Shares/DroboApps/encore.tgz
rmdir $R$APP
mkdir -p $DRI && mount --bind $R$DRI $DRI            # same paths outside the chroot
useradd -M -u 1000 -s /bin/false admin 2>/dev/null
echo "BusyBox: $(dev 'busybox 2>&1 | head -1')"

echo "== Stock firmware Samba first (as nasd would start it)"
check "stock Samba 3.4 smbpasswd creates user (tdbsam)" dev "printf 'drobo-test-pw\ndrobo-test-pw\n' | /usr/bin/smbpasswd -c $DRI/System/samba/conf/smb.conf -a -s Admin"
check "passdb.tdb written by Samba 3.4" test -s $DRI/System/samba/security/passdb.tdb
check "stock smbd 3.4 starts" dev "/sbin/smbd -s $DRI/System/samba/conf/smb.conf"
sleep 4

cp $DRI/System/samba/security/passdb.tdb /tmp/passdb.orig
echo "== Install exactly like the Drobo: DroboApps.sh (BusyBox tar), output captured like nasd"
check "DroboApps.sh install returns within 120s with stdout closed" sh -c "timeout 120 chroot $R /bin/sh /usr/bin/DroboApps.sh install | cat > /tmp/apps.out"
sed 's/^/        out: /' /tmp/apps.out
check "tgz unpacked and removed" sh -c "test -x $APP/service.sh && ! test -e $DRI/Shares/DroboApps/encore.tgz"
sleep 5
echo "        $(dev "sh $APP/service.sh status" | tr '\n' ' ')"
check "status reports Samba 4" sh -c "chroot $R /bin/sh $APP/service.sh status | grep -q 'encore (Samba 4)'"
check "bind mount visible in chroot" dev "grep -q ' /sbin/smbd ' /proc/mounts"
check "stock pid replaced by symlink" test -L $DRI/System/samba/security/smbd-smb.conf.pid
check "SMB3.1.1 works" $APP/bin/smbclient -L localhost -N -m SMB3_11
check "Samba 4 authenticates a Samba 3.4 user (SMB3 + encryption)" sh -c "$APP/bin/smbclient //localhost/Private -U Admin%drobo-test-pw -m SMB3_11 --client-protection=encrypt -c 'put /etc/hostname x.txt; ls' | grep -q x.txt"
check "wrong password rejected by Samba 4" sh -c "! $APP/bin/smbclient //localhost/Private -U admin%nope -m SMB3 -c ls"
check "web login with the Dashboard user" sh -c "curl -sk -H 'X-Encore: 1' -X POST https://localhost:8443/api/login -d '{\"user\":\"Admin\",\"password\":\"drobo-test-pw\"}' | grep -q '\"ok\":true'"
check "original passdb.tdb untouched by Samba 4" sh -c "cmp -s $DRI/System/samba/security/passdb.tdb /tmp/passdb.orig"
check "SMB1 now refused" sh -c "! $APP/bin/smbclient -L localhost -N -m NT1 --option='client min protocol=NT1' -c quit"
check "web admin up" sh -c "curl -sk https://localhost:8443/api/session | grep -q authenticated"
check "watcher alive" dev "kill -0 \$(cat $APP/var/run/watcher.pid)"

echo "== nasd-style reload (Dashboard adds a share, nasd HUPs smbd)"
mkdir -p $DRI/Shares/Media
printf '[Media]\npath = %s/Shares/Media\nread only = no\nguest ok = yes\n' $DRI >> $DRI/System/samba/conf/smb.conf
dev "/usr/bin/killall -HUP smbd"
sleep 12
check "new share appears in generated config" grep -q '^\[Media\]' $APP/var/etc/smb.conf
check "new share served" sh -c "$APP/bin/smbclient -L localhost -N -m SMB3 | grep -q Media"

echo "== nasd-style restart (killall -KILL smbd; /sbin/smbd -s ...)"
dev "/usr/bin/killall -KILL smbd nmbd; sleep 1; /sbin/smbd -s $DRI/System/samba/conf/smb.conf"
sleep 5
check "wrapper restarted Samba 4" sh -c "$APP/bin/smbclient -L localhost -N -m SMB3_11 | grep -q Media"

echo "== Revert and stop"
check "samba-off restores stock" dev "sh $APP/service.sh samba-off"
sleep 4
check "stock Samba still authenticates the user after revert" sh -c "$APP/bin/smbclient //localhost/Private -U Admin%drobo-test-pw -m NT1 --option='client min protocol=NT1' -c ls | grep -q x.txt"
check "stock Samba 3.4 back" sh -c "$APP/bin/smbclient -L localhost -N -m NT1 --option='client min protocol=NT1' 2>&1 | grep -q 'Samba V. 3.4'"
check "samba-on again" dev "sh $APP/service.sh samba-on"
sleep 4
check "Samba 4 back" $APP/bin/smbclient -L localhost -N -m SMB3_11
check "service.sh stop" dev "sh $APP/service.sh stop"
check "no Encore mounts left" sh -c "! grep -qE 'sbin/(smbd|nmbd)|avahi/services' /proc/mounts"
echo "== Encore log"; sed 's/^/        /' $APP/var/log/encore.log | tail -15
echo; echo "RESULT: $PASS passed, $FAILN failed"
EOS
