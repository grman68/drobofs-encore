-- Build the Avahi static-service directory that service.sh bind-mounts over
-- /etc/avahi/services: the stock service files plus SMB, device-info (Finder
-- icon) and _adisk (Time Machine) records for shares marked as backup targets.
local R = require("encore")

local S = R.load_settings()
local extras = R.load_json(R.SHARES_JSON, {})
local dir = R.VAR .. "/avahi"
local stock = R.VAR .. "/avahi-stock"
os.execute(string.format("mkdir -p '%s' '%s'", dir, stock))

-- Snapshot the firmware's own service files the first time (before the bind mount hides them).
local bound = R.read_file("/proc/mounts"):find(" /etc/avahi/services ", 1, true)
if not bound then
  os.execute(string.format("cp -f /etc/avahi/services/*.service '%s'/ 2>/dev/null", stock))
end
os.execute(string.format("rm -f '%s'/*.service; cp -f '%s'/*.service '%s'/ 2>/dev/null", dir, stock, dir))

local function xml_escape(s)
  return (tostring(s):gsub("&", "&amp;"):gsub("<", "&lt;"):gsub(">", "&gt;"):gsub('"', "&quot;"))
end

local has_devinfo = R.capture(string.format("grep -l _device-info '%s'/*.service", stock)) ~= ""
local services = {}
services[#services + 1] = "  <service><type>_smb._tcp</type><port>445</port></service>"
if not has_devinfo then
  services[#services + 1] = string.format(
    "  <service><type>_device-info._tcp</type><port>0</port><txt-record>model=%s</txt-record></service>",
    xml_escape(S.BONJOUR_MODEL or "Xserve"))
end

if S.SMB_MACOS == "1" then
  local disks, n = {}, 0
  for _, sec in ipairs(R.nasd_shares()) do
    local ex = extras[sec.name]
    if ex and ex.timemachine then
      disks[#disks + 1] = string.format("<txt-record>dk%d=adVN=%s,adVF=0x82</txt-record>", n, xml_escape(sec.name))
      n = n + 1
    end
  end
  if n > 0 then
    services[#services + 1] = "  <service><type>_adisk._tcp</type><port>9</port>"
      .. "<txt-record>sys=waMa=0,adVF=0x100</txt-record>" .. table.concat(disks) .. "</service>"
  end
end

local xml = [[<?xml version="1.0" standalone='no'?>
<!DOCTYPE service-group SYSTEM "avahi-service.dtd">
<!-- Generated by Encore -->
<service-group>
  <name replace-wildcards="yes">%h</name>
]] .. table.concat(services, "\n") .. "\n</service-group>\n"

if S.SMB_ENABLED == "1" then
  assert(R.write_file(dir .. "/encore-smb.service", xml, "644"))
end
print("avahi: wrote services to " .. dir)
