-- Generate Samba 4's smb.conf from nasd's (Drobo Dashboard) smb.conf plus
-- Encore settings (var/settings.conf) and per-share extras (var/shares.json).
--
-- nasd stays the owner of share definitions and users; we translate its
-- Samba 3.4 config into a Samba 4 one and layer modern defaults on top.
local R = require("encore")

local S = R.load_settings()
local extras = R.load_json(R.SHARES_JSON, {})
local nasd = R.parse_ini(R.read_conf(R.NASD_SMB_CONF))
local nasd_global = nasd[1]

local out = {}
local function emit(fmt, ...) out[#out + 1] = string.format(fmt, ...) end
local function kv(k, v) if v ~= nil and v ~= "" then emit("   %s = %s", k, v) end end

-- [global] parameters from nasd that are safe to carry over to Samba 4.
local GLOBAL_KEEP = {
  ["workgroup"] = true, ["netbios name"] = true, ["server string"] = true,
  ["map to guest"] = true, ["guest account"] = true,
  ["force user"] = true, ["force group"] = true,
  ["veto files"] = true, ["delete veto files"] = true, ["hide dot files"] = true,
  ["socket options"] = true, ["use sendfile"] = true, ["max stat cache size"] = true,
  ["interfaces"] = true, ["bind interfaces only"] = true,
  ["hosts allow"] = true, ["hosts deny"] = true,
  ["local master"] = true, ["preferred master"] = true, ["os level"] = true,
  ["wins support"] = true, ["wins server"] = true, ["name resolve order"] = true,
  ["dns proxy"] = true, ["deadtime"] = true, ["max smbd processes"] = true,
  ["dos charset"] = true, ["unix charset"] = true, ["create mask"] = true,
  ["directory mask"] = true, ["force create mode"] = true, ["force directory mode"] = true,
}

-- Share parameters we never copy (Samba 3 module paths, removed options).
local SHARE_DROP = {
  ["vfs objects"] = true, ["vfs object"] = true, ["preexec"] = true, ["postexec"] = true,
  ["root preexec"] = true, ["root postexec"] = true, ["magic script"] = true,
}

local V = R.VAR
local macos = S.SMB_MACOS == "1"
local base_vfs = macos and "catia fruit streams_depot" or ""

emit("# Generated by Encore from %s -- do not edit.", R.NASD_SMB_CONF)
emit("# Change settings in the Encore web admin; edit shares/users in Drobo Dashboard.")
emit("[global]")

local security
for _, p in ipairs(nasd_global.params) do
  if p.k == "security" then
    security = p.v:lower()
  elseif GLOBAL_KEEP[p.k] then
    kv(p.k, p.v)
  end
end
-- Samba 4 dropped share-level security; emulate it with guest mapping.
kv("security", "user")
if security == "share" then kv("map to guest", "Bad User") end

emit("   # --- Encore: protocol and security")
kv("server min protocol", S.SMB_MIN_PROTOCOL)
kv("server max protocol", S.SMB_MAX_PROTOCOL)
kv("server smb encrypt", S.SMB_ENCRYPT)
kv("server signing", S.SMB_SIGNING == "required" and "mandatory" or S.SMB_SIGNING)
kv("ntlm auth", S.SMB_MIN_PROTOCOL == "NT1" and "yes" or "ntlmv2-only")
if R.uses_tdbsam() then
  R.sync_passdb()
  kv("passdb backend", "tdbsam:" .. R.PASSDB_COPY)
else
  kv("passdb backend", "smbpasswd:" .. R.SMBPASSWD)
end
kv("server role", "standalone server")
kv("restrict anonymous", "0")

emit("   # --- Encore: state lives in the DroboApp, pid files where nasd expects them")
kv("pid directory", R.SAMBA_SEC)
kv("private dir", V .. "/samba/private")
kv("lock directory", V .. "/samba/lock")
kv("state directory", V .. "/samba/state")
kv("cache directory", V .. "/samba/cache")
kv("ncalrpc dir", V .. "/samba/ncalrpc")
kv("log file", V .. "/log/samba.log")
kv("max log size", "2000")
kv("log level", S.SMB_LOG_LEVEL)
kv("logging", "file")

emit("   # --- Encore: Linux 2.6.22 / ext3 without xattrs")
kv("ea support", "no")
kv("store dos attributes", "no")
kv("map archive", "no")
kv("map hidden", "no")
kv("map system", "no")
kv("map readonly", "no")
kv("kernel oplocks", "no")
kv("kernel share modes", "no")
kv("posix locking", "no")
kv("smbd:force process locks", "yes")
kv("durable handles", "yes")
kv("smb2 leases", "yes")
kv("server multi channel support", "no")
-- Starting RPC helpers on demand takes >7s on this CPU and clients time out;
-- smbd-wrap starts samba-dcerpcd up front with only the services we need.
kv("rpc start on demand helpers", "no")
-- Each rpcd_* worker takes several seconds to start here: run one of each, forever.
for _, d in ipairs({ "rpcd_classic", "rpcd_winreg", "rpcd_lsad", "rpcd_epmapper" }) do
  kv(d .. ":num_workers", "1")
  kv(d .. ":idle_seconds", "2000000")
end
kv("strict sync", "no")
kv("load printers", "no")
kv("printing", "bsd")
kv("printcap name", "/dev/null")
kv("disable spoolss", "yes")
kv("unix extensions", "no")
kv("wide links", "no")

if S.SMB_NETBIOS == "1" then
  kv("disable netbios", "no")
else
  kv("disable netbios", "yes")
  kv("smb ports", "445")
end

if macos then
  emit("   # --- Encore: macOS (Finder, Time Machine)")
  kv("vfs objects", base_vfs)
  kv("fruit:aapl", "yes")
  kv("fruit:model", S.BONJOUR_MODEL or "Xserve")
  kv("fruit:metadata", "stream")
  kv("fruit:resource", "file")
  kv("fruit:posix_rename", "yes")
  kv("fruit:veto_appledouble", "no")
  kv("fruit:nfs_aces", "no")
  kv("fruit:wipe_intentionally_left_blank_rfork", "yes")
  kv("fruit:delete_empty_adfiles", "yes")
  kv("readdir_attr:aapl_max_access", "no")
  kv("hide files", "/.streams/#recycle/")
  -- streams_depot normally tags files with an xattr; this ext3 has none.
  kv("streams_depot:check_valid", "no")
end

local count = 0
for i = 2, #nasd do
  local sec = nasd[i]
  local lname = sec.name:lower()
  if lname ~= "homes" and lname ~= "printers" then
    count = count + 1
    local ex = extras[sec.name] or {}
    emit("")
    emit("[%s]", sec.name)
    for _, p in ipairs(sec.params) do
      if not SHARE_DROP[p.k] and not (p.v or ""):match("^/lib/") then
        if not (ex.hidden and p.k == "browseable") then kv(p.k, p.v) end
      end
    end
    if ex.hidden then kv("browseable", "no") end
    if ex.encrypt and ex.encrypt ~= "" and ex.encrypt ~= "default" then
      kv("server smb encrypt", ex.encrypt)
    end
    local vfs = base_vfs
    if ex.recycle then
      vfs = (vfs .. " recycle"):gsub("^ ", "")
      kv("recycle:repository", "#recycle")
      kv("recycle:keeptree", "yes")
      kv("recycle:versions", "yes")
      kv("recycle:touch", "yes")
      kv("recycle:exclude", "._*,*.tmp,~$*,.DS_Store")
      kv("recycle:exclude_dir", "#recycle,.streams,.TemporaryItems")
    end
    if vfs ~= base_vfs then kv("vfs objects", vfs) end
    if ex.timemachine and macos then
      kv("fruit:time machine", "yes")
      if ex.tm_max_size and ex.tm_max_size:match("^%d+[KMGT]?$") then
        kv("fruit:time machine max size", ex.tm_max_size)
      end
    end
  end
end

os.execute("mkdir -p '" .. V .. "/etc'")
assert(R.write_file(R.GEN_SMB_CONF, table.concat(out, "\n") .. "\n", "644"))
print(string.format("smbconf: wrote %s (%d shares)", R.GEN_SMB_CONF, count))
